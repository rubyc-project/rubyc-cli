def resolve_import(inc, curdir):
    # Resolve an <Import Project="..."> to a filesystem path (or None
    # when unresolvable): `$(CommonPath)` is libraries/Common/src/
    # (one level up from the lib dir, like the fetch below);
    # `$(MSBuildThisFileDirectory)` is the importing file's dir.
    p = inc.replace('\\', '/')
    if '$(CommonPath)' in p:
        tail = p.split('$(CommonPath)', 1)[1].lstrip('/')
        return os.path.normpath(os.path.join('../Common/src', tail))
    if '$(MSBuildThisFileDirectory)' in p:
        tail = p.split('$(MSBuildThisFileDirectory)', 1)[1].lstrip('/')
        return os.path.normpath(os.path.join(curdir, tail))
    if '$(' in p:
        return None
    return os.path.normpath(os.path.join(curdir, p))
def fetch_to(link, tail, src, sub):
    link = (link or '').replace('\\', '/')
    dest = os.path.normpath(os.path.join('src', sub, link if link else tail))
    # Collision: a committed local source already occupies this dest
    # (e.g. Odbc's local `Common\System\Data\ProviderBase\*.cs` partials
    # vs fetched Links staged under `src/Common/`). MSBuild compiles BOTH
    # (different identities — Link vs Include path), so the fetch must
    # land elsewhere: drop the `sub` prefix and stage at the Link itself
    # (the MSBuild identity). If THAT collides too, last-wins as before
    # (genuinely ambiguous — vanishingly rare, and loud below).
    local_cs = os.path.splitext(dest)[0] + '.cs'
    if os.path.isfile(local_cs):
        alt = os.path.normpath(os.path.join('src', link if link else tail))
        if not os.path.isfile(os.path.splitext(alt)[0] + '.cs'):
            dest = alt
        else:
            print('[rubyc] warning: fetch dest %s collides twice; last-wins' % dest)
    dest = os.path.splitext(dest)[0] + '.rc'
    # A fetch happens BECAUSE a csproj entry included it: record an
    # explicit keep so explicit-list pruning (which exempts only
    # `src/Common/` and `src/CoreCLR/`) never drops a redirected fetch
    # staged outside those dirs. (Not `generated`: fetched files count
    # as real staged sources for the ref-fallback emptiness scan.)
    decisions[os.path.normpath(dest)] = True
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(src, 'rb') as fsrc, open(dest, 'wb') as fdst:
        fdst.write(fsrc.read())
def link_of(child):
    # `<Link>` arrives as an attribute (`Link="..."`) or a child
    # element (`<Link>...</Link>`); both forms occur across the
    # library projects.
    link = child.get('Link') or ''
    if not link:
        for sub in child:
            if local(sub.tag) == 'Link' and sub.text:
                link = sub.text
                break
    return link.replace('\\', '/')
custom_props = {}
def harvest_props(group, inherited_cond):
    # MSBuild lets a project define its own path shorthands
    # (`<XmlSources>System\Xml</XmlSources>`, then
    # `<Compile Include="$(XmlSources)\Foo.cs" />`, as in
    # DataContractSerialization). Without expansion those entries look
    # unresolvable and their files silently drop out of the build.
    # Collect simple unconditional values only — anything with `$`,
    # `[`, `]` or `;` (references, functions, lists) stays out.
    # Later definitions win, like MSBuild.
    gcond = combine_conds(group.get('Condition'), inherited_cond)
    if gcond and not eval_cond(gcond):
        return
    for prop in group:
        if len(list(prop)):
            continue
        name = local(prop.tag)
        if not name:
            continue
        val = (prop.text or '').strip().replace('\\', '/')
        if not val or any(c in val for c in '$[];'):
            continue
        custom_props[name] = val
def walk(node, inherited_cond, curdir, is_import, depth):
    # One project per process: a fresh document root resets the custom
    # property table (imported roots add to it, in visit order).
    if depth == 0 and not is_import and local(node.tag) == 'Project':
        custom_props.clear()
    # MSBuild: a <Compile> inherits its <ItemGroup>'s Condition when
    # it carries none of its own; when it carries one, the two AND
    # together (see combine_conds) — the group gate alone decides
    # files like the entire WasiHttpHandler group under
    # `TargetPlatformIdentifier == 'wasi'`.
    for child in node:
        tag = local(child.tag)
        if tag == 'PropertyGroup':
            # Custom path shorthands (`<XmlSources>...`), harvested in
            # document order so use-before-define stays empty, as in
            # MSBuild evaluation.
            harvest_props(child, inherited_cond)
            continue
        if tag == 'Import' and depth < 4:
            # Shared build files (`*.projitems`, `*.targets`): their
            # <Compile> entries join the importing project (e.g.
            # Crypto's AsnWriter extensions). The import's own
            # Condition gates everything inside.
            imp = child.get('Project') or ''
            icond = combine_conds(child.get('Condition'), inherited_cond)
            if icond and not eval_cond(icond):
                continue
            ipath = resolve_import(imp, curdir)
            if not ipath:
                continue
            try:
