# Build hooks for pulled dotnet/runtime libraries (generated by pull-dotnet.sh).
# Invoked by the .rcp as:
#   bash ../rc-hooks.sh prebuild src
#   bash ../rc-hooks.sh postbuild <Lib> src
# with CWD = the project directory (src/libraries/<Lib>/).
set -euo pipefail

