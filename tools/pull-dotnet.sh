# Extract referenced library names from a lib's .csproj files:
# <ProjectReference Include="..."> paths point at sibling libraries
# (usually via $(LibrariesProjectRoot)<Lib>\src\<Lib>.csproj, with
# Windows backslashes). Prints one lib name per line.
project_refs() {
  local dir="$1" inc norm cand ref
  grep -rhoE '<ProjectReference Include="[^"]+"' "$dir/src" --include='*.csproj' 2>/dev/null \
    | sed -E 's/.*Include="//; s/"$//' \
    | while IFS= read -r inc; do
      norm="${inc//\\//}"
      cand="$norm"
      # Preferred: segment right after $(LibrariesProjectRoot).
      case "$norm" in
        *'$(LibrariesProjectRoot)'*) cand="${norm#*'$(LibrariesProjectRoot)'}"; cand="${cand#/}" ;;
        *) # Fallback: parent directory of a /src/ segment.
          case "$norm" in
            */src/*)
              cand="${norm%%/src/*}"
              cand="${cand##*/}"
              ;;
            *) continue ;;
          esac
          printf '%s\n' "$cand"
          continue
          ;;
      esac
      ref="${cand%%/*}"
      [ -n "$ref" ] && printf '%s\n' "$ref"
    done | sort -u
}

