def expand(s):
    return re.sub(r'\$\(([^)]+)\)', lambda m: KNOWN.get(m.group(1), ''), s)
def eval_atom(atom):
    m = re.match(r"^\s*'(.*)'\s*(==|!=)\s*'(.*)'\s*$", atom)
    if not m:
        return True  # unknown shape (functions, etc.): keep the file
    raw_a, op, raw_b = m.group(1), m.group(2), m.group(3)
    a, b = expand(raw_a), expand(raw_b)
    # Platform family: `'unix'` groups AND `'linux'` groups both belong
    # in a Linux build (likewise `'unix'`+`'osx'` on macOS) — a scalar
    # TPI cannot equal both, so compare set membership instead. Proven
    # necessary both ways: ConsolePal.Unix.cs has no Linux alternative,
    # and NetworkInformation's `.Linux.cs` PALs have no Unix one
    # (`.UnknownUnix.cs` is illumos-only); collisions are all `partial`
    # merges. Other platforms keep scalar behavior.
    tpi = os.environ.get('RUBYC_TPI', 'unix')
    family = {'unix': ('unix', 'linux'), 'linux': ('unix', 'linux'),
              'osx': ('unix', 'osx')}.get(tpi)
    if family is not None and 'TargetPlatformIdentifier' in (raw_a + raw_b):
        lit = b if 'TargetPlatformIdentifier' in raw_a else a
        if lit == '':
            # Agnostic (`== ''`) belongs everywhere; negated
            # (`!= ''`, "a platform is set") is likewise true.
            return True
        eq = lit in family
        return eq if op == '==' else (not eq)
    eq = (a == b)
    return eq if op == '==' else (not eq)
def strip_outer(cond):
    # Remove one balanced outer paren layer, repeatedly: (A) -> A.
    # Bails (returns as-is) unless the first '(' matches the last ')'.
    while len(cond) >= 2 and cond[0] == '(' and cond[-1] == ')':
        depth = 0
        ok = True
        for i, ch in enumerate(cond):
            if ch == '(':
                depth += 1
            elif ch == ')':
                depth -= 1
                if depth == 0 and i != len(cond) - 1:
                    ok = False
                    break
        if not ok or depth != 0:
            break
        cond = cond[1:-1].strip()
    return cond
def eval_cond(cond):
    # Recursive descent over top-level operators (OR lowest precedence,
    # so it splits first): AND binds tighter, and parenthesized groups
    # from combine_conds (`(A And B) And (C Or D)`) evaluate inside-out.
    # A flat regex split mis-evaluates nested groups (it once dropped
    # Unix files by reducing `(A And B) And (C Or D)` to garbage atoms).
    cond = strip_outer(cond.strip())
    or_parts = split_top(cond, 'or')
    if len(or_parts) > 1:
        return any(eval_cond(p) for p in or_parts)
    and_parts = split_top(cond, 'and')
    if len(and_parts) > 1:
        return all(eval_cond(p) for p in and_parts)
    return eval_atom(cond)
def split_top(cond, keyword):
    # Split on a Boolean operator only at paren-depth zero and outside
    # single quotes: `$(...)` property expansions contain parens, and
    # combine_conds emits parenthesized groups (`(A) And (B)`). A naive
    # regex split breaks both (it once let OSX-only files into Linux
    # builds by splitting `(OSX or MacCat) And (Unix)` on the inner
    # `or`). Operator match is case-insensitive, whitespace-bounded
    # (MSBuild style).
    parts, depth, cur, in_quote, i = [], 0, [], False, 0
    n, kw = len(cond), keyword.lower()
    while i < n:
        ch = cond[i]
        if ch == "'":
            in_quote = not in_quote
            cur.append(ch)
            i += 1
            continue
        if not in_quote:
            if ch == '(':
                depth += 1
            elif ch == ')':
                depth -= 1
        hit = (
            not in_quote
            and depth == 0
            and cond[i:i + len(kw)].lower() == kw
            and (i == 0 or cond[i - 1].isspace())
            and (i + len(kw) >= n or cond[i + len(kw)].isspace())
        )
        if hit:
            parts.append(''.join(cur))
            cur = []
            i += len(kw)
            continue
        cur.append(ch)
        i += 1
    parts.append(''.join(cur))
    return parts
def combine_conds(item_cond, group_cond):
    # MSBuild ANDs an item's Condition with its ItemGroup's: a file
    # with its own Condition inside a gated group (e.g.
    # NativeLibrary.Windows.cs with `'$(FeatureMono)' != 'true'`
    # inside the `TargetsWindows` group) is out when EITHER is false.
    # `or`-chaining here leaked Windows-only files into Linux builds.
    if item_cond and group_cond:
        return f"({item_cond}) And ({group_cond})"
    return item_cond or group_cond
def local(tag):
    return tag.rsplit('}', 1)[-1]
