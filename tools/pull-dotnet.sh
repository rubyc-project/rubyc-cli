#!/usr/bin/env bash
#
# pull-dotnet.sh — vendor dotnet/runtime's src/libraries into RubyC projects.
#
# Standalone (git + coreutils only; no dotnet SDK required). Re-runnable:
#   * first run  -> blobless sparse clone of dotnet/runtime (src/libraries only)
#   * later runs -> git fetch (update-checking friendly) + regenerate projects
#
# The vendored tree keeps upstream .cs files byte-for-byte (git-clean, so
# `git log` / `git diff` / `git pull` detect upstream upgrades). Each generated
# <Lib>.rcp copies .cs -> .rc in its pre-build hook and deletes the .rc copies
# in its post-build hook, so the compiler builds native .rc while the tree
# stays in its upstream .cs form at all times.
#
# Usage:
#   tools/pull-dotnet.sh                          # clone/update + regenerate all
#   RUBYC_DOTNET_BRANCH=release/9.0 tools/pull-dotnet.sh
#   RUBYC_DOTNET_DEPTH=500 tools/pull-dotnet.sh   # deeper history for diffing
#
set -euo pipefail

URL="${RUBYC_DOTNET_URL:-https://github.com/dotnet/runtime.git}"
BRANCH="${RUBYC_DOTNET_BRANCH:-main}"
DEPTH="${RUBYC_DOTNET_DEPTH:-200}"
SRC_REL="src/libraries"
# System.Private.CoreLib also compiles its CoreCLR-VM partials
# (`String.CoreCLR.cs` with `FastAllocateString`, `Enum.CoreCLR.cs`
# with `GetEnumInfo`, `Array.CoreCLR.cs` with `Rank`, ...): without
# these, CoreLib sources reference undeclared members. Pulled
# alongside the libraries; only CoreLib's build consumes them.
CORECLR_REL="src/coreclr/System.Private.CoreLib/src"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
DEST="$ROOT/dotnet-runtime"
LIBS_DIR="$DEST/$SRC_REL"
SOLUTION="$LIBS_DIR/dotnet-runtime.rcs"
HOOKS_HELPER="$LIBS_DIR/rc-hooks.sh"

log() { printf '\033[1;34[pull\033[0m %s\n' "$*"; }
die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

command -v git >/dev/null 2>&1 || die "git is required"

# ---------- 1. clone or update ----------
if [ -d "$DEST/.git" ]; then
  log "updating existing clone at $DEST"
  git -C "$DEST" fetch --depth "$DEPTH" origin "$BRANCH"
  git -C "$DEST" sparse-checkout set "$SRC_REL" "$CORECLR_REL"
  git -C "$DEST" checkout "$BRANCH"
  git -C "$DEST" merge --ff-only "origin/$BRANCH"
else
  log "cloning $URL (branch=$BRANCH depth=$DEPTH sparse=$SRC_REL,$CORECLR_REL)"
  [ -e "$DEST" ] && die "$DEST exists but is not a git clone; remove it first"
  git clone --filter=blob:none --no-checkout --depth "$DEPTH" --sparse "$URL" "$DEST"
  git -C "$DEST" sparse-checkout set "$SRC_REL" "$CORECLR_REL"
  git -C "$DEST" checkout "$BRANCH"
fi
SHA="$(git -C "$DEST" rev-parse --short HEAD)"
log "at $BRANCH @ $SHA"

# ---------- 2. keep the clone pristine for update-checking ----------
# Ignore the generated project files via the per-repo local exclude list
# (.git/info/exclude): it is never committed, never pushed, and never touches
# a tracked file, so `git status`/`git diff`/`git log`/`git pull` stay clean
# for detecting upstream dotnet/runtime upgrades.
EXCLUDE="$DEST/.git/info/exclude"
marker="# RubyC generated project files (local-only ignore)"
if grep -qF "$marker" "$EXCLUDE" 2>/dev/null; then
  : # already present
else
  {
    printf '\n%s\n' "$marker"
    printf 'src/libraries/**/*.rcp\n'
    printf 'src/libraries/**/*.rcs\n'
    printf 'src/libraries/rc-hooks.sh\n'
    printf 'src/libraries/**/*.rc\n'
  } >> "$EXCLUDE"
fi

# ---------- 3. shared build-hooks helper ----------
# Lives at src/libraries/rc-hooks.sh; each <Lib>.rcp calls it as ../rc-hooks.sh
# (run with CWD = the project dir, i.e. src/libraries/<Lib>/).
cat > "$HOOKS_HELPER" <<'HOOKS'
