def flag_value(txt, kind):
    # <EnableDefaultItems>/EnableDefaultCompileItems> value in a file
    # (True/False/None when absent). Case-insensitive, like MSBuild.
    m = re.search(r'<\s*' + kind + r'\s*>\s*(true|false)\s*<', txt, re.IGNORECASE)
    if not m:
        return None
    return m.group(1).lower() == 'true'
def defaults_off(proj, start):
    # Whether SDK default globs are OFF (explicit-list only).
    # Precedence (MSBuild import order): the project file's own
    # setting first (e.g. Nrbf's `<EnableDefaultItems>true`), then
    # Directory.Build.props walking up, nearest wins (libraries/
    # sets false globally; shims/ re-enables true for its subtree).
    # SDK default with nothing found: globs ON (False).
    # Explicit-list mode prunes unlisted on-disk sources (an unlisted
    # file like HMACShared.cs — an other-target alternative to the
    # listed HMACStatic.cs — would otherwise duplicate types); glob
    # mode keeps everything not explicitly excluded.
    try:
        with open(proj, 'r', errors='ignore') as f:
            txt = f.read()
    except OSError:
        txt = ''
    items = flag_value(txt, 'EnableDefaultItems')
    comp = flag_value(txt, 'EnableDefaultCompileItems')
    if items is False or comp is False:
        return True
    if items is True and comp is not False:
        return False
    d = os.path.normpath(start)
    for _ in range(6):
        for name in ('Directory.Build.props', 'Directory.Build.targets'):
            try:
                with open(os.path.join(d, name), 'r', errors='ignore') as f:
                    txt = f.read()
            except OSError:
                continue
            items = flag_value(txt, 'EnableDefaultItems')
            comp = flag_value(txt, 'EnableDefaultCompileItems')
            if items is False or comp is False:
                return True
            if items is True and comp is not False:
                return False
        parent = os.path.dirname(os.path.abspath(d))
        if parent == os.path.abspath(d):
            break
        d = parent
    return False
